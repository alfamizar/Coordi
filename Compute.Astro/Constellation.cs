    /// <summary>
    /// Constellation identification and boundary polygons (IAU boundaries, Roman 1875).
    /// </summary>
    public static class Constellations
    {
        /// <summary>The constellation's full name, e.g. "Ursa Major" for <see cref="Constellation.UMA"/>.</summary>
        public static string FullName(this Constellation c) => Names[(int)c];

        /// <summary>
        /// Identifies the constellation containing the given celestial body at the given time.
        /// </summary>
        /// <param name="jd">The Julian Day of the observation.</param>
        /// <param name="rightAscensionDeg">Right Ascension in degrees (0 to 360).</param>
        /// <param name="declinationDeg">Declination in degrees (-90 to +90).</param>
        /// <returns>The containing <see cref="Constellation"/>.</returns>
        public static Constellation Of(double jd, double rightAscensionDeg, double declinationDeg)
        {
            var b1875 = Coordinates.PrecessToB1875(jd, rightAscensionDeg, declinationDeg);
            return FindB1875(b1875.RightAscensionDeg / 15.0, b1875.DeclinationDeg);
        }

        /// <summary>
        /// The B1875 boundary polygon of <paramref name="c"/> as (RA degrees, Dec degrees) vertex
        /// pairs, for chart rendering. RA values of polygons crossing 0h are stored unwrapped
        /// (may exceed 360°), which is exactly what a renderer wants — trig is periodic and paths
        /// stay continuous. Precess each vertex with <see cref="Coordinates.PrecessFromB1875"/>
        /// before drawing in today's sky.
        /// </summary>
        public static IReadOnlyList<(double RaDeg, double DecDeg)> BoundaryB1875(Constellation c)
        {
            var raw = Bounds[(int)c];
            var result = new List<(double, double)>(raw.Length / 2);
            for (var i = 0; i < raw.Length; i += 2)
            {
                result.Add((raw[i] * 15.0, raw[i + 1]));
            }

            return result;
        }

        /// <summary>
        /// Identifies the constellation containing the given equatorial coordinates.
        /// The coordinates must be precessed to the B1875.0 epoch.
        /// </summary>
        /// <param name="ra1875">Right Ascension in hours (0 to 24).</param>
        /// <param name="dec1875">Declination in degrees (-90 to +90).</param>
        /// <returns>The containing <see cref="Constellation"/>.</returns>
        internal static Constellation FindB1875(double ra1875, double dec1875)
        {
            // The B1875 polygons might have RA wrapped (e.g. 23 to 25 instead of 23 to 1).
            var raWrapped = ra1875 + 24.0;
            var boxes = BoundingBoxes;
            for (var i = 0; i < Bounds.Length; i++)
            {
                var testRa = IsWrapped[i] && ra1875 < 12.0 ? raWrapped : ra1875;

                // Reject on the bounding box first. The crossing test only counts edges to the
                // right of the point, so a point outside the box always scores zero crossings —
                // this is exactly equivalent, and skips the vertex walk for ~85 of the 88.
                var b = i * BoundingBoxStride;
                if (testRa < boxes[b] || testRa > boxes[b + 1] ||
                    dec1875 < boxes[b + 2] || dec1875 > boxes[b + 3])
                {
                    continue;
                }

                if (PointInPolygon(testRa, dec1875, Bounds[i]))
                {
                    return (Constellation)i;
                }
            }

            // Fallback for edge cases (e.g. exactly on a border or near poles).
            return dec1875 > 0 ? Constellation.UMI : Constellation.OCT;
        }

        private static bool PointInPolygon(double x, double y, double[] poly)
        {
            var inside = false;
            var p1X = poly[0];
            var p1Y = poly[1];
            var numPoints = poly.Length / 2;
            for (var i = 1; i <= numPoints; i++)
            {
                var idx = i % numPoints * 2;
                var p2X = poly[idx];
                var p2Y = poly[idx + 1];
                if (y > Math.Min(p1Y, p2Y) && y <= Math.Max(p1Y, p2Y) && x <= Math.Max(p1X, p2X))
                {
                    var xints = p1Y != p2Y ? (y - p1Y) * (p2X - p1X) / (p2Y - p1Y) + p1X : p1X;
                    if (p1X == p2X || x <= xints)
                    {
                        inside = !inside;
                    }
                }

                p1X = p2X;
                p1Y = p2Y;
            }

            return inside;
        }

        private const int BoundingBoxStride = 4;

        private static double[] BuildBoundingBoxes()
        {
            var boxes = new double[Bounds.Length * BoundingBoxStride];
            for (var i = 0; i < Bounds.Length; i++)
            {
                var poly = Bounds[i];
                double raMin = double.MaxValue, raMax = double.MinValue;
                double decMin = double.MaxValue, decMax = double.MinValue;
                for (var v = 0; v < poly.Length; v += 2)
                {
                    var ra = poly[v];
                    var dec = poly[v + 1];
                    if (ra < raMin) raMin = ra;
                    if (ra > raMax) raMax = ra;
                    if (dec < decMin) decMin = dec;
                    if (dec > decMax) decMax = dec;
                }

                var b = i * BoundingBoxStride;
                boxes[b] = raMin;
                boxes[b + 1] = raMax;
                boxes[b + 2] = decMin;
                boxes[b + 3] = decMax;
            }

            return boxes;
        }

